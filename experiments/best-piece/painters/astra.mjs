  S(arc(.835,.632,.075,.079,4.3,5.6),C.white,.011,.8);
  for(const [x,y,r] of [[.31,.49,.014],[.739,.353,.012],[.762,.384,.006],[.38,.205,.009]]) {
    ring(x,y,r,r,C.mist,.01,2.7,6.9);
    S([[x-r*.45,y-r*.75],[x,y-r]],C.white,.01,.75);
  }
  S([[.386,.904],[.448,.914],[.532,.907]],C.teal,.027,.45,.65);
  S([[.548,.933],[.622,.925]],C.gold,.016,.38,.65);
